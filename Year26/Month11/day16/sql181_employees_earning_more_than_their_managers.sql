-- =============================================================
-- LeetCode 181. 超过经理收入的员工 (Easy)
-- https://leetcode.cn/problems/employees-earning-more-than-their-managers/
-- =============================================================
-- 表 Employee (id, name, salary, managerId)
--   id        主键
--   managerId 指向本表另一行的 id，即"这个人的经理是谁"
--             经理本人也在表里，所以这是一张自引用表
--
-- 题意
--   找出工资比自己的经理高的员工，返回列名必须是 Employee。
--
-- 关键点
--   managerId 可能为 NULL（这个人没有经理，比如老板），
--   这类行不应该出现在结果里 —— 两种写法都天然避开了它。
-- =============================================================


-- -------------------------------------------------------------
-- 写法一：相关子查询
--   对外层每一行，都去表里查一次"我的经理工资是多少"。
--   直观，但每一行都要执行一次子查询。
-- -------------------------------------------------------------

SELECT
    name AS Employee
FROM
    Employee e1
WHERE
    e1.salary > (
        SELECT salary
        FROM Employee e2
        WHERE e2.id = e1.managerId
    );


-- -------------------------------------------------------------
-- 写法二：自连接（更推荐）
--   把同一张表当成两张表用：e1 是员工，e2 是他的经理。
--   e1.managerId = e2.id 就是"找到我的经理那一行"。
--   数据量大时，自连接能利用 id 上的索引，通常比相关子查询快。
-- -------------------------------------------------------------

SELECT
    e1.name AS Employee
FROM
    Employee e1
JOIN
    Employee e2 ON e1.managerId = e2.id
WHERE
    e1.salary > e2.salary;


-- 面试可延伸
--   1. 自连接的 JOIN 条件必须写 managerId = id，写反了会得到相反的结果。
--   2. 若 managerId 指向一个不存在的人，自连接会丢掉这行，
--      子查询则会得到 NULL 比较（同样不匹配）—— 两种写法结果一致。
